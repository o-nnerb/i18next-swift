// Writes Sources/I18next/BCP47AliasData.swift: the language, region, script and sign-language aliases that
// `Intl.getCanonicalLocales` applies (the Unicode CLDR alias data, as the system's ICU ships it). They are read from
// JavaScriptCore, the same engine the conformance scenarios run i18next in, so the port and the oracle agree.
//
//   swift Scripts/generate-bcp47-aliases.swift Sources/I18next/BCP47AliasData.swift
//
// macOS only (JavaScriptCore).

import Foundation
import JavaScriptCore

guard CommandLine.arguments.count == 2 else {
    FileHandle.standardError.write(Data("usage: generate-bcp47-aliases.swift <output.swift>\n".utf8))
    exit(2)
}

let script = """
function canon(tag) { try { return Intl.getCanonicalLocales(tag)[0]; } catch (e) { return null; } }
var alpha = 'abcdefghijklmnopqrstuvwxyz';
var ALPHA = alpha.toUpperCase();
var out = { languages: {}, regions: {}, regionByLanguage: {}, scripts: {}, signLanguages: {} };

var twoLetter = [];
for (var a of alpha) for (var b of alpha) {
    var two = a + b;
    twoLetter.push(two);
    var r2 = canon(two);
    if (r2 !== two) out.languages[two] = r2;
    for (var c of alpha) {
        var three = two + c;
        var r3 = canon(three);
        if (r3 !== three) out.languages[three] = r3;
    }
}

var regionCodes = [];
for (var a of ALPHA) for (var b of ALPHA) regionCodes.push(a + b);
for (var i = 0; i < 1000; i++) regionCodes.push(('00' + i).slice(-3));
regionCodes.forEach(function (region) {
    var result = canon('en-' + region);
    if (result !== 'en-' + region) out.regions[region] = result.slice(3);
});

// A territory that was split can answer differently for the languages spoken in one of its parts (`SU`: `ka` → `GE`).
Object.keys(out.regions).forEach(function (region) {
    var byLanguage = {};
    twoLetter.forEach(function (lang) {
        if (canon(lang) !== lang) return;
        var result = canon(lang + '-' + region);
        var replacement = result && result.slice(lang.length + 1);
        if (replacement && replacement !== out.regions[region]) byLanguage[lang] = replacement;
    });
    if (Object.keys(byLanguage).length > 0) out.regionByLanguage[region] = byLanguage;
});

ALPHA.split('').forEach(function (a) {
    ALPHA.split('').forEach(function (b) {
        var region = a + b;
        var result = canon('sgn-' + region);
        if (result && result.indexOf('sgn') !== 0) out.signLanguages[region] = result;
    });
});

for (var a of alpha) for (var b of alpha) for (var c of alpha) for (var d of alpha) {
    var s = (a + b + c + d);
    var title = s[0].toUpperCase() + s.slice(1);
    var result = canon('und-' + title);
    if (result !== 'und-' + title) out.scripts[title] = result.slice(4);
}
JSON.stringify(out);
"""

let context = JSContext()!
guard let json = context.evaluateScript(script)?.toString(),
    let data = json.data(using: .utf8),
    let tables = try JSONSerialization.jsonObject(with: data) as? [String: Any]
else { fatalError("could not read the alias tables") }

func flat(_ name: String) -> [String: String] { tables[name] as! [String: String] }

func literal(_ entries: [String: String], indent: String) -> String {
    entries.sorted { $0.key < $1.key }
        .map { "\(indent)\"\($0.key)\": \"\($0.value)\"," }
        .joined(separator: "\n")
}

var text = """
// Copyright © 1991-2025 Unicode, Inc.
// SPDX-License-Identifier: Unicode-3.0
//
// Derived from the Unicode CLDR alias data (common/supplemental/supplementalMetadata.xml), as the ICU in the system
// exposes it through `Intl.getCanonicalLocales`. See https://www.unicode.org/license.txt for the terms of use.
//
// GENERATED by Scripts/generate-bcp47-aliases.swift. Do not edit.
// swift-format-ignore-file

enum BCP47AliasData {
    /// Deprecated and ISO 639-2/3 language codes, with what replaces them (`iw` → `he`, `eng` → `en`). A replacement
    /// may carry a script or a region (`sh` → `sr-Latn`, `cnr` → `sr-ME`), which a tag that has its own keeps.
    static let languages: [String: String] = [

"""
text += literal(flat("languages"), indent: "        ") + "\n    ]\n\n"

text += """
    /// Deprecated and numeric region codes (`UK` → `GB`, `840` → `US`).
    static let regions: [String: String] = [

"""
text += literal(flat("regions"), indent: "        ") + "\n    ]\n\n"

text += """
    /// Regions that were split and so have several replacements: the first language to speak of one gets its own
    /// (`SU` is `RU`, but `ka-SU` is `ka-GE`).
    static let regionByLanguage: [String: [String: String]] = [

"""
let byLanguage = tables["regionByLanguage"] as! [String: [String: String]]
for region in byLanguage.keys.sorted() {
    text += "        \"\(region)\": [\n" + literal(byLanguage[region]!, indent: "            ") + "\n        ],\n"
}
text += "    ]\n\n"

text += """
    /// Scripts that have a replacement (`Qaai` → `Zinh`).
    static let scripts: [String: String] = [

"""
text += literal(flat("scripts"), indent: "        ") + "\n    ]\n\n"

text += """
    /// `sgn-US` is American Sign Language: the sign language of a region has a language code of its own.
    static let signLanguages: [String: String] = [

"""
text += literal(flat("signLanguages"), indent: "        ") + "\n    ]\n}\n"

try text.write(toFile: CommandLine.arguments[1], atomically: true, encoding: .utf8)
print("wrote \(CommandLine.arguments[1])")
