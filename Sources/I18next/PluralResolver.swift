/// CLDR plural categories.
public enum PluralCategory: String, Sendable, CaseIterable {
    case zero, one, two, few, many, other
}

/// CLDR plural operands for a number (https://unicode.org/reports/tr35/tr35-numbers.html#Operands).
///
/// Compact-notation operands (`c`, `e`) are always 0: a plain number has no exponent.
struct PluralOperands: Sendable, Equatable {
    /// Absolute value.
    let n: Double
    /// Integer digits.
    let i: Int
    /// Count of visible fraction digits, with trailing zeros.
    let v: Int
    /// Count of visible fraction digits, without trailing zeros.
    let w: Int
    /// Visible fraction digits, with trailing zeros.
    let f: Int
    /// Visible fraction digits, without trailing zeros.
    let t: Int
    let c = 0
    let e = 0

    /// From a number. A `Double` carries no trailing zeros, so `1.0` is `1` (as with `Intl.PluralRules`).
    init(_ value: Double) {
        guard value.isFinite else {
            self.init(n: .infinity, integer: "0", fraction: "")
            return
        }
        let absolute = abs(value)
        let (integer, fraction) = Self.digits(of: "\(absolute)")
        self.init(n: absolute, integer: integer, fraction: fraction == "0" ? "" : fraction)
    }

    /// From a decimal string such as `"1.50"`, keeping its visible fraction digits.
    init?(decimal text: String) {
        let unsigned = text.hasPrefix("-") ? String(text.dropFirst()) : text
        guard let value = Double(unsigned), !unsigned.contains("e"), !unsigned.contains("E") else { return nil }
        let parts = unsigned.split(separator: ".", omittingEmptySubsequences: false)
        guard parts.count <= 2, parts[0].allSatisfy(\.isASCII) else { return nil }
        self.init(n: value, integer: String(parts[0]), fraction: parts.count == 2 ? String(parts[1]) : "")
    }

    private init(n: Double, integer: String, fraction: String) {
        self.n = n
        self.i = Int(integer) ?? 0
        self.v = fraction.count
        self.f = Int(fraction) ?? 0

        var trimmed = Substring(fraction)
        while trimmed.last == "0" { trimmed = trimmed.dropLast() }
        self.w = trimmed.count
        self.t = Int(trimmed) ?? 0
    }

    /// Splits `Double.description` into integer and fraction digits, expanding exponent notation
    /// (`1e-05` → `0` / `00001`, `1.5e+16` → `15000000000000000` / ``).
    static func digits(of description: String) -> (integer: String, fraction: String) {
        var mantissa = Substring(description)
        var exponent = 0
        if let marker = description.firstIndex(where: { $0 == "e" || $0 == "E" }) {
            mantissa = description[..<marker]
            exponent = Int(description[description.index(after: marker)...].drop { $0 == "+" }) ?? 0
        }

        let parts = mantissa.split(separator: ".", omittingEmptySubsequences: false)
        var integer = String(parts[0])
        var fraction = parts.count > 1 ? String(parts[1]) : ""

        if exponent > 0 {
            let shift = min(exponent, fraction.count)
            integer += fraction.prefix(shift)
            fraction = String(fraction.dropFirst(shift))
            integer += String(repeating: "0", count: exponent - shift)
        } else if exponent < 0 {
            let missing = -exponent
            let padded = String(repeating: "0", count: max(0, missing - integer.count)) + integer
            let split = padded.index(padded.endIndex, offsetBy: -missing)
            fraction = String(padded[split...]) + fraction
            integer = padded[..<split].isEmpty ? "0" : String(padded[..<split])
        }
        return (integer, fraction)
    }
}

typealias PluralRule = @Sendable (PluralOperands) -> PluralCategory

/// Resolves plural categories and the key suffixes used by i18next v4 JSON (`key_one`, `key_other`, …),
/// from the CLDR tables in `CLDRPluralData` (generated by `Scripts/generate-plurals.py`).
public struct PluralResolver: Sendable {
    public var separator: String

    public init(separator: String = "_") {
        self.separator = separator
    }

    public func category(for count: Double, lng: String, ordinal: Bool = false) -> PluralCategory {
        category(for: PluralOperands(count), lng: lng, ordinal: ordinal)
    }

    func category(for operands: PluralOperands, lng: String, ordinal: Bool = false) -> PluralCategory {
        Self.rule(for: lng, ordinal: ordinal)?(operands) ?? .other
    }

    /// `_one`, `_other`, … or `_ordinal_one`, …
    public func suffix(for count: Double, lng: String, ordinal: Bool = false) -> String {
        let category = category(for: count, lng: lng, ordinal: ordinal)
        return separator + (ordinal ? "ordinal" + separator : "") + category.rawValue
    }

    /// The exact tag (`pt-PT`), then its language (`pt`). An unknown language gets English cardinal rules and
    /// no ordinal rules, which is what `Intl.PluralRules` falls back to.
    static func rule(for lng: String, ordinal: Bool) -> PluralRule? {
        let table = ordinal ? CLDRPluralData.ordinal : CLDRPluralData.cardinal
        if let rule = table[lng] ?? table[LanguageUtils().languagePart(lng)] { return rule }
        return ordinal ? nil : CLDRPluralData.cardinal["en"]
    }
}
